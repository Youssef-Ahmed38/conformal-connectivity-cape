def m(v, d=3):
    v = np.asarray(v, float)
    return f"{v.mean():.{d}f}" if len(v) == 1 else f"{v.mean():.{d}f}\\,$\\pm$\\,{v.std():.{d}f}"


def mean(v):
    return float(np.mean(v))


def cmp(ph, key, metric):
    for k, d, p, s in F[ph]["_comparisons"][key]:
        if k == metric:
            return d, p, s
    raise KeyError(key)


def pfmt(p):
    if p < 1e-3:
        e = int(np.floor(np.log10(p))); return f"{p / 10 ** e:.1f}\\times10^{{{e}}}"
    return f"{p:.3f}"


def score_ablation(reps=50):
    """AUROC(error) and ECE (isotonic) of each connection score, 3 seeds per backbone, random 10/10 image splits."""
    out = {}
    for fam, runs in SEEDS.items():
        out[fam] = {s: {"auroc": [], "ece": []} for s in SCORES}
        for r in runs:
            _, pairs = load_run(r)
            rng = np.random.default_rng(0)
            A = {s: [] for s in SCORES}
            for _ in range(reps):
                p = rng.permutation(len(pairs))
                c, t = cat([pairs[i] for i in p[:10]]), cat([pairs[i] for i in p[10:]])
                for s in SCORES:
                    A[s].append(assess(c, t, s, (0.1,)))
            for s in SCORES:
                out[fam][s]["auroc"].append(float(np.nanmean([a["auroc_err"] for a in A[s]])))
                out[fam][s]["ece"].append(float(np.nanmean([a["ece"] for a in A[s]])))
    return out


def crc_curve(alphas=(0.05, 0.075, 0.1, 0.125, 0.15, 0.2), reps=50):
    res = {}
    for fam, runs in SEEDS.items():
        rr = {a: {"risk": [], "trusted": [], "caught": []} for a in alphas}
        for r in runs:
            _, pairs = load_run(r)
            c = crc_splits(pairs, 16, "mcbn", alphas, reps=reps)
            for a in alphas:
                rr[a]["risk"].append(c[a]["risk"]); rr[a]["trusted"].append(c[a]["trusted"]); rr[a]["caught"].append(c[a]["errors_flagged"])
        res[fam] = rr
    return res


